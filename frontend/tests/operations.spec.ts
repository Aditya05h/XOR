test('operator previews alternate telemetry columns and imports a full year',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Open telemetry workspace'}).click()
 await expect(page.getByRole('heading',{name:'Telemetry ingestion',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Download 12-month synthetic telemetry'})).toHaveCount(0)
 const rows=['date,usage,limit'];for(let i=0;i<365;i++)rows.push(`${new Date(Date.UTC(2025,0,1+i)).toISOString()},${30+i/10},100`)
 await page.getByLabel('Upload telemetry CSV').setInputFiles({name:'history.csv',mimeType:'text/csv',buffer:Buffer.from(rows.join('\n'))})
 await page.getByLabel('rack_id shared value').fill('R-01')
 await page.getByLabel('tenant_id shared value').fill('T1')
 await page.getByLabel('resource_type shared value').fill('STORAGE')
 await page.getByRole('button',{name:'Import readings',exact:true}).click()
 await expect(page.getByRole('heading',{name:/365 accepted.*0 rejected/})).toBeVisible()
 await page.getByRole('button',{name:/Analyse R-01/}).click()
 await expect(page.getByRole('button',{name:'Evaluate capacity risk'})).toBeVisible()
 await expect(page.getByText('Offline trained model:',{exact:false})).toBeVisible()
 await page.screenshot({path:'../tmp/telemetry-ingestion.png',fullPage:true})
})

