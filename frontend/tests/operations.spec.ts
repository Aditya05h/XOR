import {test,expect} from '@playwright/test'
test('operator completes telemetry to human review, preserves evidence and explores archive',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.getByRole('button',{name:'Start local synthetic demo'}).click()
 await expect(page.getByText('Facility operator',{exact:false})).toBeVisible()
 await expect(page.getByText('Incident stream connected',{exact:false})).toBeVisible()
 await page.getByRole('button',{name:'R-04',exact:true}).click()
 await page.getByRole('button',{name:'Explode selected rack',exact:true}).click()
 await expect(page.getByRole('button',{name:'Reassemble rack',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Illustrative airflow',exact:true}).click()
 await page.getByRole('button',{name:'Load early-warning scenario',exact:true}).click()
 await expect(page.getByLabel('Historical telemetry timeline')).toHaveValue('230')
 await page.getByRole('button',{name:'Monitor R-04',exact:false}).click()
 await expect(page.getByRole('status').filter({hasText:'incident(s) created'})).toBeVisible()
 await page.getByRole('button',{name:'incidents',exact:true}).click()
 await page.getByRole('button',{name:'Process highest priority'}).click()
 await expect(page.getByRole('heading',{name:'Paused for your decision'})).toBeVisible()
 await page.getByLabel('Decision notes').fill('Review demand assumptions with tenant owner; retain advisory only')
 await page.getByRole('button',{name:'defer',exact:true}).click()
 await expect(page.getByText('DEFERRED BY OPERATOR',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'approve',exact:true}).click()
 await expect(page.getByText('APPROVED BY OPERATOR',{exact:true})).toBeVisible()
 await page.getByText(/Audit trail ·/).click()
 await expect(page.getByText('Operator approve recorded;', {exact:false})).toBeVisible()
 await page.screenshot({path:'../tmp/decision-console.png',fullPage:true})
 await page.getByRole('button',{name:'evaluation',exact:true}).click()
 await expect(page.getByText('mae utilization pct',{exact:false})).toBeVisible({timeout:30000})
 await page.getByRole('button',{name:'archive',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Archive examples and original datasets'})).toBeVisible()
 await expect(page.getByText('ao02',{exact:false}).first()).toBeVisible()
 expect(errors).toEqual([])
})
test('connected mobile view and reverse assembly have no overflow',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await page.getByRole('button',{name:'Start local synthetic demo'}).click()
 await page.getByRole('button',{name:'R-04',exact:true}).click()
 await page.getByRole('button',{name:'Explode selected rack',exact:true}).click()
 await page.getByRole('button',{name:'Reassemble rack',exact:true}).click()
 await expect(page.getByRole('button',{name:'Explode selected rack',exact:true})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
 await page.screenshot({path:'../tmp/connected-mobile.png',fullPage:true})
})
